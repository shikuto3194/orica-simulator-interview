/**
 * 継続 vs 誘発(即時) 効果判定の再発防止検出 — 「Xを満たしている間、フィールドに置き」型
 * イディオムを機械的に洗い出す純粋関数群。
 *
 * 背景 (2026-07-18, BSLH01-T07..T17【アーツ】cluster): 「属性値が…満たしている間、
 * フィールドに置き」を「置き」が終止形/連用形=強制だから常時効果、と誤って判断した
 * (強制/任意の軸と常時/誘発の軸を混同)。正しい判定根拠は「発揮開始タイミングを示す
 * 語彙(『〜時』見出し・「〜になったとき」・アタックステップ等の named step 指定)が
 * 原文に無いこと」。qa-016 (external-qa/qaData.js) が「『離れるとき』などの発揮タイミング
 * の指定が無い常時効果であるため、スタックタイミング元になりません」と明記しこの基準を
 * 裏付ける。正源: manual/ai-reference/10_rules/03c_effect-text-interpretation.md
 * §「常時/継続 vs 誘発/即時」。
 *
 * このモジュールは「間、フィールドに置き/置ける」型イディオム自体を検出するのみで、
 * 継続/誘発いずれが正しいかを判定しない (それはカードごとの読解が要る)。目的は
 * 「この分類ミスが起きやすいイディオムに触れた」ことを機械的にフラグし、
 * 03c の当該節を読んだかどうかに関わらず注意を促すこと (再発防止のバックストップ)。
 */

// 「Xを満たしている間、フィールドに置き/置ける」型: 条件付き継続的フィールド在places idiom。
// 検証済み (2026-07-18): 全カードコーパスに対し 11 件ヒット、全て BSLH01-T07..T17
// (対象クラスタそのもの)。false positive 0 件を確認済み。
export const CONTINUITY_PLACEMENT_RE =
  /満たしている間、[^。]*フィールドに置[きけ]/;

export function hasContinuityPlacementWording(text) {
  if (!text) return false;
  return CONTINUITY_PLACEMENT_RE.test(text);
}
