/** 不明な旧データも内部識別子を表示しない。辞書検索は自身のプロパティに限定。 */
export function effectActionLabel(kind: string): string {
  return Object.hasOwn(EFFECT_ACTION_LABELS, kind)
    ? EFFECT_ACTION_LABELS[kind as Action["kind"]]
    : "効果";
}

/** 明示の日本語本文・固有名詞を保持し、旧 snapshot の raw kind だけを辞書で復元する。 */
export function localizeEffectLabel(label: string): string {
  return Object.hasOwn(EFFECT_ACTION_LABELS, label)
    ? effectActionLabel(label)
    : /^[a-z][a-zA-Z0-9_-]*$/.test(label)
      ? "効果"
      : label;
}

export function getChoiceLabelForAction(action: Action): string {
  if (action.kind === "discard" && action.destination === "deck_bottom") {
    return "デッキの下に戻す";
  }
  if (action.kind === "draw") {
    if (action.position === "bottom") return "デッキの下からドロー";
    if (action.position === "top") return "デッキの上からドロー";
  }
  return effectActionLabel(action.kind);
}
